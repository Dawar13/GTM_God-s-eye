"""Write data/RESEARCH_LOG.md from the research files (PHASE_1 §1.3.8).

Every research file already records its pages, conflicts and open items, so
the log is generated from them and can't drift. Hand-written notes (pilot
calibration, batch observations) live in data/research/NOTES.md and are
included verbatim.
"""

from collections import Counter
from urllib.parse import urlparse

from atlas.config import DATA, RESEARCH

LOG_PATH = DATA / "RESEARCH_LOG.md"
NOTES_PATH = RESEARCH / "NOTES.md"

QUESTIONS = {
    "investor_A": "Tier A profile: identity, terms, thesis, funds, partners, ≥ 8 rounds",
    "investor_B": "Tier B profile: identity, stages, thesis, latest fund, ≥ 3 rounds",
    "competitor": "Competitor profile: identity, funding history, product, investors",
    "round": "Verify a seed-list round: amount, date, stage, investors",
}


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def _domains(pages: list[dict]) -> str:
    counts = Counter(urlparse(p["url"]).netloc.removeprefix("www.") for p in pages)
    top = ", ".join(f"{d} ×{n}" if n > 1 else d for d, n in counts.most_common(6))
    more = len(counts) - 6
    return f"{len(pages)} pages: {top}" + (f", +{more} more domains" if more > 0 else "")


def _result(f: dict) -> str:
    kind = f["entity_type"]
    if kind == "investor":
        facts = ", ".join(sorted(f["facts"]))
        return (
            f"{f['status']}; facts: {facts or 'none'}; funds {len(f['funds'])}, "
            f"partners {len(f['partners'])}, rounds {len(f['rounds'])}"
        )
    if kind == "competitor":
        return f"{f['category']} / {f['layer']}; rounds {len(f['rounds'])}"
    return f"{f['verdict']}"


def _entity(f: dict) -> str:
    name = f.get("name") or (f.get("company") or {}).get("name") or f.get("seed_company")
    return f"{name} (`{f['key']}`)"


def write_log(files: list[dict]) -> None:
    lines = [
        "# Research log",
        "",
        "Generated by the pipeline from `data/research/cache/` (one row per research file) and",
        "`data/research/NOTES.md` (hand-written notes). Do not edit the table by hand.",
        "",
        "Conflicts between sources are listed per entity; the chosen value and the reason are in",
        "the research file and in `data/processed/anomalies.json`.",
        "",
    ]
    if NOTES_PATH.exists():
        lines += [NOTES_PATH.read_text(encoding="utf-8").rstrip(), ""]
    lines += [
        "## Entities",
        "",
        "| date | entity | questions | sources checked | result | conflicts | open items |",
        "|---|---|---|---|---|---|---|",
    ]
    for f in sorted(files, key=lambda x: (x["researched_at"], x["key"])):
        q = QUESTIONS.get(
            f"investor_{f['tier']}" if f["entity_type"] == "investor" else f["entity_type"], ""
        )
        conflicts = "; ".join(
            f"{c['field']}: {' vs '.join(c['values'])} → {c['chosen']}" for c in f["conflicts"]
        )
        row = [
            f["researched_at"],
            _entity(f),
            q,
            _domains(f["pages"]),
            _result(f),
            conflicts or "none",
            "; ".join(f["open_items"]) or "none",
        ]
        lines.append("| " + " | ".join(_cell(c) for c in row) + " |")
    lines.append("")
    LOG_PATH.write_text("\n".join(lines), encoding="utf-8", newline="\n")
