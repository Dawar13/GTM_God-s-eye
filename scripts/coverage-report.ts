/**
 * Coverage report (PHASE_1 §9.1): per-tier field coverage, source and
 * confidence mix, record counts and progress against the Phase 1 exit targets.
 * Writes docs/COVERAGE.md; the self-audit section is kept from the previous
 * file (scripts/self-audit.ts writes it).
 *
 *   pnpm coverage:report
 */
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import {
  getBenchmarks,
  getCompanies,
  getCompetitors,
  getFunds,
  getInvestors,
  getLegalNotes,
  getPartners,
  getRounds,
} from "../src/lib/data/index";
import type { Investor, Round } from "../src/lib/schema";

const OUT = path.join(process.cwd(), "docs", "COVERAGE.md");
const AUDIT_START = "<!-- self-audit -->";

const pct = (n: number, d: number) => (d ? `${Math.round((100 * n) / d)}%` : "—");

/** A round counts as sourced when at least one source is not a user-supplied list. */
const sourced = (r: Round) => r.sources.some((s) => s.kind !== "user_supplied");
const researched = (i: Investor) => i.sources.some((s) => s.kind !== "user_supplied");

const FIELDS: [string, (i: Investor) => boolean][] = [
  ["type", (i) => i.type !== null],
  ["region", (i) => i.region !== null],
  ["hq_country", (i) => i.hq_country !== null],
  ["website", (i) => i.website !== null],
  ["stages", (i) => i.stages.length > 0],
  ["check size", (i) => i.check_min_usd !== null || i.check_max_usd !== null],
  ["leads", (i) => i.leads !== null],
  ["thesis_text", (i) => i.thesis_text !== null],
  ["sector_weights", (i) => i.sector_weights !== null],
  ["application_url", (i) => i.application_url !== null],
  ["accepts_cold_inbound", (i) => i.accepts_cold_inbound !== "unknown"],
  ["invests_in_indian_founders", (i) => i.invests_in_indian_founders !== "unknown"],
  ["requires_us_entity", (i) => i.requires_us_entity !== "unknown"],
  ["portfolio_count_reported", (i) => i.portfolio_count_reported !== null],
  ["≥ 1 fund", (i) => i.funds.length > 0],
  ["≥ 1 partner", (i) => i.partners.length > 0],
];

function mix<T extends string>(values: T[]): string {
  const counts = new Map<T, number>();
  for (const v of values) counts.set(v, (counts.get(v) ?? 0) + 1);
  return [...counts.entries()]
    .sort((a, b) => b[1] - a[1])
    .map(([k, n]) => `${k} ${pct(n, values.length)}`)
    .join(" · ");
}

async function main() {
  const [investors, funds, partners, rounds, companies, competitors, benchmarks, legal] =
    await Promise.all([
      getInvestors(),
      getFunds(),
      getPartners(),
      getRounds(),
      getCompanies(),
      getCompetitors(),
      getBenchmarks(),
      getLegalNotes(),
    ]);

  const roundsBy = new Map<string, Round[]>();
  for (const r of rounds)
    for (const id of [
      ...r.lead_investor_ids,
      ...r.participant_investor_ids,
      ...r.unspecified_investor_ids,
    ])
      roundsBy.set(id, [...(roundsBy.get(id) ?? []), r]);
  const sourcedRounds = (i: Investor) => (roundsBy.get(i.id) ?? []).filter(sourced).length;

  const tier = (t: "A" | "B" | "C") => investors.filter((i) => i.tier === t);
  const a = tier("A");
  const b = tier("B");
  const aWestern = a.filter((i) => i.region === "western");
  const aIndia = a.filter((i) => i.region === "india");
  const full = (i: Investor) => researched(i) && sourcedRounds(i) >= 8;
  const shallow = (i: Investor) => researched(i) && sourcedRounds(i) >= 3;

  const lines: string[] = [
    "# Coverage",
    "",
    `Generated by \`pnpm coverage:report\` on ${new Date().toISOString().slice(0, 10)}. Targets from PHASE_1 §10.`,
    "",
    "## Progress against exit targets",
    "",
    "| Target | Now | Needed |",
    "|---|---:|---:|",
    `| Tier A Western investors researched with ≥ 8 sourced rounds | ${aWestern.filter(full).length} | 60 |`,
    `| Tier A India investors researched with ≥ 8 sourced rounds | ${aIndia.filter(full).length} | 10 |`,
    `| Tier B investors researched (≥ 3 sourced rounds) | ${b.filter(shallow).length} | 200 |`,
    `| Competitors profiled | ${competitors.length} | all of PROJECT_CONTEXT §7 |`,
    `| Rounds with a non-list source | ${rounds.filter(sourced).length} | 600 |`,
    `| Companies | ${companies.length + competitors.length} | 400 |`,
    "",
    "## Record counts",
    "",
    "| Investors | Funds | Partners | Rounds | Companies | Competitors | Benchmarks | Legal notes |",
    "|---:|---:|---:|---:|---:|---:|---:|---:|",
    `| ${investors.length} | ${funds.length} | ${partners.length} | ${rounds.length} | ${companies.length} | ${competitors.length} | ${benchmarks.length} | ${legal.length} |`,
    "",
    "## Investor field coverage by tier",
    "",
    "Share of investors in the tier with the field known. Tier A and B are researched; Tier C is fund-list and seed-list data only.",
    "",
    `| Field | Tier A (${a.length}) | Tier B (${b.length}) | Tier C (${tier("C").length}) |`,
    "|---|---:|---:|---:|",
    ...FIELDS.map(
      ([name, has]) =>
        `| ${name} | ${pct(a.filter(has).length, a.length)} | ${pct(b.filter(has).length, b.length)} | ${pct(tier("C").filter(has).length, tier("C").length)} |`,
    ),
    `| researched (any non-list source) | ${pct(a.filter(researched).length, a.length)} | ${pct(b.filter(researched).length, b.length)} | ${pct(tier("C").filter(researched).length, tier("C").length)} |`,
    "",
    "## Source kind and confidence mix",
    "",
    "| Records | Source kinds | Confidence |",
    "|---|---|---|",
    ...(
      [
        ["investors", investors],
        ["funds", funds],
        ["rounds", rounds],
        ["companies", companies],
        ["competitors", competitors],
        ["partners", partners],
        ["benchmarks", benchmarks],
        ["legal notes", legal],
      ] as const
    ).map(
      ([name, recs]) =>
        `| ${name} | ${mix(recs.flatMap((r) => r.sources.map((s) => s.kind)))} | ${mix(recs.map((r) => r.confidence))} |`,
    ),
    "",
    "## Legal notes by topic",
    "",
    "| Topic | Notes | Distinct sources | Primary sources |",
    "|---|---:|---:|---:|",
    ...[...new Set(legal.map((n) => n.topic))].sort().map((topic) => {
      const notes = legal.filter((n) => n.topic === topic);
      const urls = new Set(notes.flatMap((n) => n.sources.map((s) => s.url)));
      const primary = new Set(
        notes.flatMap((n) => n.sources.filter((s) => s.kind === "primary").map((s) => s.url)),
      );
      return `| ${topic} | ${notes.length} | ${urls.size} | ${primary.size} |`;
    }),
    "",
  ];

  let audit = `${AUDIT_START}\n## Self-audit\n\nNot run yet (\`pnpm self-audit\`).\n`;
  try {
    const previous = await readFile(OUT, "utf8");
    const at = previous.indexOf(AUDIT_START);
    if (at >= 0) audit = previous.slice(at);
  } catch {
    // first run
  }
  await writeFile(OUT, lines.join("\n") + "\n" + audit);
  console.log(`coverage:report wrote ${path.relative(process.cwd(), OUT)}`);
}

main().catch((e: unknown) => {
  console.error(e);
  process.exit(1);
});
